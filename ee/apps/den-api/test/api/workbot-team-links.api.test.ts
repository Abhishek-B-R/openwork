import assert from "node:assert/strict"
import { after, test } from "node:test"
import { bootDen, field, summary, text } from "./harness.js"

const den = await bootDen()
after(() => den.close())

test("team links use the token's live member and organization, not browser headers", async () => {
  const { orgId, owner } = await den.createOrg(await den.signUp("Workspace Owner"), "Team workspace")
  const other = await den.createOrg(owner, "Other workspace")
  const member = await den.newMember(owner, orgId, "Team Member")
  const ownerToken = await den.mintMcpToken(owner, orgId)
  const memberToken = await den.mintMcpToken(member, orgId)
  const session = (token: string, requestedOrg = orgId) => den.request(token, "GET", "/v1/workbot/session", { orgId: requestedOrg })
  assert.equal((await den.request(null, "GET", "/v1/workbot/session")).status, 401)
  const off = await session(ownerToken)
  assert.equal(off.status, 200, summary(off))
  assert.deepEqual(field(off.body, "teamLinks"), { enabled: false, settings: true, apps: true })
  assert.equal((await den.setFeature(orgId, "workbotTeamLinks", true)).status, 200)
  const on = await session(ownerToken, other.orgId)
  assert.equal(on.status, 200, summary(on))
  assert.equal(field(on.body, "organization", "id"), orgId)
  assert.deepEqual(field(on.body, "teamLinks"), { enabled: true, settings: true, apps: true })
  const noAdmin = await session(memberToken)
  assert.deepEqual(field(noAdmin.body, "teamLinks"), { enabled: true, settings: false, apps: false })
  const destination = await den.as(member, orgId)("GET", "/v1/org/workbot-settings")
  assert.equal(destination.status, 403, summary(destination))
  const promote = await den.as(owner, orgId)("POST", `/v1/members/${member.memberId}/role`, { role: "admin" })
  assert.equal(promote.status, 200, summary(promote))
  assert.deepEqual(field((await session(memberToken)).body, "teamLinks"), { enabled: true, settings: true, apps: true })
  const demote = await den.as(owner, orgId)("POST", `/v1/members/${member.memberId}/role`, { role: "member" })
  assert.equal(demote.status, 200, summary(demote))
  // Removing admin authority also revokes the old grant; a new member grant has no admin hints.
  assert.equal((await session(memberToken)).status, 401)
  const signedInAgain = await den.signIn(member.email)
  assert.equal(signedInAgain.status, 200, summary(signedInAgain))
  const demotedToken = await den.mintMcpToken({ ...member, token: text(field(signedInAgain.body, "token"), "fresh member session") }, orgId)
  assert.deepEqual(field((await session(demotedToken)).body, "teamLinks"), { enabled: true, settings: false, apps: false })
  const removed = await den.as(owner, orgId)("DELETE", `/v1/members/${member.memberId}`)
  assert.ok(removed.status < 300, summary(removed))
  assert.equal((await session(demotedToken)).status, 401)
  assert.equal((await den.setFeature(orgId, "workbotTeamLinks", false)).status, 200)
  assert.equal(field((await session(ownerToken)).body, "teamLinks", "enabled"), false)
  assert.deepEqual(field((await session(ownerToken)).body, "teamLinks"), { enabled: false, settings: true, apps: true })
})
